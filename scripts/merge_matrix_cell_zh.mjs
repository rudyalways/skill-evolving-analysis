function autoGloss(en) {
  if (EXACT_GLOSS[en]) return EXACT_GLOSS[en];
  if (/^\*\*[\d./]+\*\*$/.test(en)) return en;
  if (/^\d+\/\d+$/.test(en)) return en;
  if (/^[★◐❌]$/.test(en)) return en;
  if (/^\d+$/.test(en)) return en;

  let out = en;
  out = out.replace(/\bdir\b/g, '目录');
  out = out.replace(/\bfile\b/g, '文件');
  out = out.replace(/\blayer\b/g, '层');
  out = out.replace(/\bscan\b/g, '扫描');
  out = out.replace(/\btoggle\b/g, '开关');
  out = out.replace(/\bsearch\b/g, '搜索');
  out = out.replace(/\bexport\b/g, '导出');
  out = out.replace(/\bsync\b/g, '同步');
  out = out.replace(/\btitle\b/g, '标题');
  out = out.replace(/\bfacts\b/g, '事实');
  out = out.replace(/\bsteps\b/g, '步骤');
  out = out.replace(/\breject\b/g, 'reject');
  out = out.replace(/\bsession\b/g, 'session');
  out = out.replace(/\bcompact\b/g, 'compact');
  return out === en ? en : out;
}

let added = 0;
for (const cell of untranslated) {
  if (cfg.exact[cell] !== undefined) continue;
  const zh = autoGloss(cell);
  if (zh !== cell) {
    cfg.exact[cell] = zh;
    added += 1;
  }
}

fs.writeFileSync(cfgPath, JSON.stringify(cfg, null, 2) + '\n');
console.log(`Merged ${added} auto exact cell translations`);
